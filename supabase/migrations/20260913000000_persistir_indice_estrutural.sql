CREATE TABLE diagnosticos_indice (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id BIGINT NOT NULL,
  id_fato TEXT NOT NULL,
  codigo TEXT NOT NULL,
  categoria TEXT NOT NULL,
  arquivo_origem_id TEXT,
  evidencia_caminho TEXT NOT NULL,
  evidencia_inicio_linha INTEGER NOT NULL CHECK (evidencia_inicio_linha > 0),
  evidencia_inicio_coluna INTEGER NOT NULL CHECK (evidencia_inicio_coluna > 0),
  evidencia_fim_linha INTEGER NOT NULL CHECK (evidencia_fim_linha > 0),
  evidencia_fim_coluna INTEGER NOT NULL CHECK (evidencia_fim_coluna > 0),
  CONSTRAINT diagnosticos_indice_evidencia_ordenada CHECK (
    evidencia_fim_linha > evidencia_inicio_linha
    OR (
      evidencia_fim_linha = evidencia_inicio_linha
      AND evidencia_fim_coluna >= evidencia_inicio_coluna
    )
  ),
  CONSTRAINT diagnosticos_indice_id_fato_unico UNIQUE (snapshot_id, id_fato),
  CONSTRAINT diagnosticos_indice_codigo_valido CHECK (
    codigo IN ('ERRO_SINTATICO', 'COMMONJS_NAO_SUPORTADO', 'IMPORT_DINAMICO_NAO_RESOLVIDO')
  ),
  CONSTRAINT diagnosticos_indice_categoria_valida CHECK (categoria IN ('sintaxe', 'limitacao')),
  CONSTRAINT diagnosticos_indice_arquivo_origem_coerente CHECK (
    arquivo_origem_id IS NULL OR arquivo_origem_id <> ''
  ),
  CONSTRAINT diagnosticos_indice_arquivo_fk
    FOREIGN KEY (snapshot_id, arquivo_origem_id)
    REFERENCES arquivos_indice(snapshot_id, id_fato)
    ON DELETE CASCADE,
  CONSTRAINT diagnosticos_indice_evidencia_fk
    FOREIGN KEY (snapshot_id, evidencia_caminho)
    REFERENCES arquivos_indice(snapshot_id, caminho)
    ON DELETE CASCADE
);
